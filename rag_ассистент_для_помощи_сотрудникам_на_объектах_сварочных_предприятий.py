# Блокируем опасные фразы
def is_safe_query(query: str) -> bool:
    q = query.lower()
    for pattern in DANGEROUS_PATTERNS:
        if pattern in q:
            return False
    return True


# Вывод результата
def ans(query):
  data = {}
  if len(query) < 20:
    data['error'] = "Мало информации. Задайте вопрос более детально."
    return data
  else:
    result = is_safe_query(query)
    if not result:
        data['error'] = """Нарушать технику безопасности КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО!\nЭто может повлечь за собой вред для здоровья или поломку оборудования."""
        return data
    else:
        response = query_engine.query(query)
        data['succes'] = response.response
        for node in response.source_nodes:
            data['metadata'] = f"\nИсточник:\nРаздел: {node.metadata.get('section')}"
            data['node'] = f"Текс: {node.text[:200]}"
        return data

